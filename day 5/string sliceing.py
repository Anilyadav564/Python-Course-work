# String Operations

s = ''
print(s)

s = 'mokshagna'
print(s)

# Concatenation
print('mokshagna' + 'Sai')

# Repetition
print('mokshagna' * 3)
print('&$' * 3)

# Indexing
s = 'Mokshagna'
print(s[5])

# Slicing
print(s[0:9:-1])
print(s[::-1])
print(s[2:6:-1])
print(s[-2:-6:-1])
print(s[-2:-8])
print(s[-8])
print(s[-8:-5])
print(s[0:9:2])

# Membership
print('mok' in s)
print('Moks' in s)